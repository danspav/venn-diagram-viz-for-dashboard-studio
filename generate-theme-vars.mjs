/**
 * Generates static/theme-vars.css from @splunk/themes token values.
 * Run automatically as part of build-preview-host.mjs, or manually:
 *   node generate-theme-vars.mjs
 */
import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import pkg from '@splunk/themes/getTheme.js';
const getTheme = pkg.default ?? pkg;

const __dirname = dirname(fileURLToPath(import.meta.url));

const TOKENS = [
    'contentColorDefault',
    'contentColorMuted',
    'backgroundColorPage',
    'backgroundColorSection',
    'backgroundColorSidebar',
    'borderColorWeak',
    'fontSizeSmall',
    'fontWeightBold',
    'fontFamily',
];

function buildVars(theme) {
    return TOKENS.map((key) => {
        const value = theme[key];
        return value != null ? `    --viz-${key}: ${value};` : null;
    })
        .filter(Boolean)
        .join('\n');
}

const light = getTheme({ family: 'enterprise', colorScheme: 'light', density: 'comfortable' });
const dark = getTheme({ family: 'enterprise', colorScheme: 'dark', density: 'comfortable' });

const css = `/* Auto-generated by generate-theme-vars.mjs — do not edit by hand */
:root[data-color-scheme='light'] {
${buildVars(light)}
}

:root[data-color-scheme='dark'] {
${buildVars(dark)}
}
`;

const outPath = resolve(__dirname, 'static/theme-vars.css');
writeFileSync(outPath, css);
console.log(`Written: ${outPath}`);
